class FmsControlStatus:
    """FMS_CONTROL_STATUS - Thrust and landing gear status. RT 12 · SA 21 · transmit (terminal to bus) · 3 words · 5 Hz.

    fmsControl.set_thrust holds thrust to 0.1 .. 0.9 (1.0 with the afterburner lit), sets throttle_position = int(thrust x 100), lights the afterburner above 0.9 and puts it out below 0.85. Before any command: thrust 0.5, throttle 50, afterburner off, gear UP.
    """
    RT: ClassVar[int] = 12
    SUBADDRESS: ClassVar[int] = 21
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 5
    WORDS: ClassVar[int] = 3

    last_cmd_seq: int = 0
    afterburner: bool = False
    gear: GearPosition = GearPosition.UNKNOWN  # The commanded gear position
    throttle_position: int = 0  # Percent, 0-100: int(thrust x 100)
    status: CmdStatus = CmdStatus.NONE  # Outcome of the last command
    thrust: float = 0.0  # LSB 1/10000, 0 .. 1, Thrust in force, 0-1

    def encode(self) -> Tuple[Status, List[int]]:
        w = [0] * 3
        result = Status.OK
        s, v = _w.check_uint(self.last_cmd_seq, 8)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 7, 0, v)
        w[1] = _w.set_bit(w[1], 15, bool(self.afterburner))
        if not is_valid(GearPosition, self.gear):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[1] = _w.set_field(w[1], 14, 13, int(self.gear))
        s, v = _w.check_uint(self.throttle_position, 7)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 12, 6, v)
        if not is_valid(CmdStatus, self.status):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[1] = _w.set_field(w[1], 3, 0, int(self.status))
        s, raw = _w.encode_scaled(self.thrust, 1, 10000, 0, 10000)
        result = worst(result, s)
        w[2] = _w.set_field(w[2], 15, 0, raw)
        return result, w

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["FmsControlStatus"]]:
        if len(words) != cls.WORDS:
            return Status.BAD_LENGTH, None
        m = cls()
        m.last_cmd_seq = _w.get_field(words[0], 7, 0)
        m.afterburner = _w.get_bit(words[1], 15)
