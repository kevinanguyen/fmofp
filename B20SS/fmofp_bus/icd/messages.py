@dataclass
class NavSolution:
    """NAV_SOLUTION - Navigation solution. RT 7 · SA 15 · transmit (terminal to bus) · 8 words · 10 Hz.

    The fused position (fuseData.NavDataFusion: one scalar Kalman filter per axis, predicted by dead reckoning every frame and corrected by each GPS fix). position_ssm and altitude_ssm are NO_COMPUTED_DATA until the first fix has been incorporated; after that the estimate is always computed, and gps_valid plus fix_age say how fresh the last fix is. gps_valid is 1 when the last GPS epoch gave a fix (at least 4 satellites, solvable geometry). clock_bias is the receiver clock bias the solver estimated.
    """
    RT: ClassVar[int] = 7
    SUBADDRESS: ClassVar[int] = 15
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 10
    WORDS: ClassVar[int] = 8

    position_ssm: Ssm = Ssm.FAILURE_WARNING  # validity of latitude, Validity of latitude and longitude
    altitude_ssm: Ssm = Ssm.FAILURE_WARNING  # validity of altitude
    gps_valid: bool = False
    sats_used: int = 0  # Satellites in the last fix, 0-12
    latitude: float = 0.0  # deg, LSB 180/2147483648, -90 .. 90, WGS-84, north positive
    longitude: float = 0.0  # deg, LSB 180/2147483648, -180 .. 179.9999999, WGS-84, east positive
    altitude: float = 0.0  # ft, LSB 1, -32768 .. 32767, Height above the WGS-84 ellipsoid, as the GPS reports it
    fix_count: int = 0  # Fixes incorporated since start, saturates at 255
    fix_age: int = 0  # Seconds since the last fix, saturates at 255; 255 before the first
    clock_bias: float = 0.0  # us, LSB 1/100, -327.68 .. 327.67, Receiver clock bias from the solver

    def encode(self) -> Tuple[Status, List[int]]:
        w = [0] * 8
        result = Status.OK
        if not is_valid(Ssm, self.position_ssm):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 15, 14, int(self.position_ssm))
        if not is_valid(Ssm, self.altitude_ssm):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 13, 12, int(self.altitude_ssm))
        w[0] = _w.set_bit(w[0], 11, bool(self.gps_valid))
        s, v = _w.check_uint(self.sats_used, 4)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 7, 4, v)
        s, raw = _w.encode_scaled(self.latitude, 45, 536870912, -1073741824, 1073741824)
        result = worst(result, s)
        w[1], w[2] = divmod(_w.to_twos32(raw), 0x10000)
        s, raw = _w.encode_scaled(self.longitude, 45, 536870912, -2147483648, 2147483647)
        result = worst(result, s)
        w[3], w[4] = divmod(_w.to_twos32(raw), 0x10000)
        s, raw = _w.encode_scaled(self.altitude, 1, 1, -32768, 32767)
        result = worst(result, s)
        w[5] = _w.set_field(w[5], 15, 0, _w.to_twos(raw, 16))
        s, v = _w.check_uint(self.fix_count, 8)
        result = worst(result, s)
        w[6] = _w.set_field(w[6], 15, 8, v)
        s, v = _w.check_uint(self.fix_age, 8)
        result = worst(result, s)
        w[6] = _w.set_field(w[6], 7, 0, v)
        s, raw = _w.encode_scaled(self.clock_bias, 1, 100, -32768, 32767)
        result = worst(result, s)
        w[7] = _w.set_field(w[7], 15, 0, _w.to_twos(raw, 16))
        return result, w

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["NavSolution"]]:
        if len(words) != cls.WORDS:
            return Status.BAD_LENGTH, None
        m = cls()
        raw = _w.get_field(words[0], 15, 14)
        if not is_valid(Ssm, raw):
            return Status.INVALID_ENUM, None
        m.position_ssm = Ssm(raw)
        raw = _w.get_field(words[0], 13, 12)
        if not is_valid(Ssm, raw):
            return Status.INVALID_ENUM, None
        m.altitude_ssm = Ssm(raw)
        m.gps_valid = _w.get_bit(words[0], 11)
        m.sats_used = _w.get_field(words[0], 7, 4)
        m.latitude = _w.decode_scaled(_w.from_twos32((words[1] << 16) | words[2]), 45, 536870912)
        m.longitude = _w.decode_scaled(_w.from_twos32((words[3] << 16) | words[4]), 45, 536870912)
        m.altitude = _w.decode_scaled(_w.from_twos(_w.get_field(words[5], 15, 0), 16), 1, 1)
        m.fix_count = _w.get_field(words[6], 15, 8)
        m.fix_age = _w.get_field(words[6], 7, 0)
        m.clock_bias = _w.decode_scaled(_w.from_twos(_w.get_field(words[7], 15, 0), 16), 1, 100)
        return Status.OK, m


