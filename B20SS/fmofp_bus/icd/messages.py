class PlantGps:
    """PLANT_GPS - GPS pseudoranges from the plant. RT 27 · SA 2 · transmit (terminal to bus) · 25 words · 1 Hz.

    What the simulated GPS receiver measures each epoch: for every satellite of the 12-satellite constellation of globalPositionSystem._build_constellation() that is at least 5 degrees above the horizon, pseudorange = geometric range + c x (receiver clock bias - satellite clock bias) + measurement noise (3 m, 1 sigma). The noise is drawn once per epoch here, in the plant; the solver in the navigation terminal is deterministic. epoch increments with each new set; a pseudorange whose satellite bit is 0 in visible_mask is not valid.
    """
    RT: ClassVar[int] = 27
    SUBADDRESS: ClassVar[int] = 2
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 1
    WORDS: ClassVar[int] = 25

    epoch: int = 0  # Increments (mod 16) with every new measurement set
    visible_mask: int = 0  # Bit n-1 = satellite n (1-12) has a valid pseudorange
    pseudorange_1: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_2: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_3: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_4: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_5: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_6: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_7: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_8: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_9: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_10: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_11: float = 0.0  # m, LSB 1/16, 0 .. 100000000
    pseudorange_12: float = 0.0  # m, LSB 1/16, 0 .. 100000000

