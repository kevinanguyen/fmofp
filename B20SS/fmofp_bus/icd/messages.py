class RdrWxScan:
    """RDR_WX_SCAN - Weather radar scan summary. RT 9 · SA 18 · transmit (terminal to bus) · 10 words · 5 Hz.

    What the last completed scan found, for the display's header and for anyone who does not reassemble the RDR_WX_PRODUCTS block. While NORMAL in an operating mode the radar sweeps the full circle over 60 minor frames (1.2 s), six azimuth degrees per frame, rendering the volume from the weather truth it latched when the sweep began; the products of a scan are published as one block when the scan completes, and products_version is the block version carrying them. The counts are what was detected before the block's record limits were applied.
    """
    RT: ClassVar[int] = 9
    SUBADDRESS: ClassVar[int] = 18
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 5
    WORDS: ClassVar[int] = 10

    scan_id: int = 0  # Id of the last completed scan, increments mod 256
    mode: WeatherMode = WeatherMode.NONE  # Mode the scan was made in; NONE when no scan has completed since the mode was left
    scanning: bool = False  # 1 = a scan is in progress
    max_turbulence: TurbulenceCategory = TurbulenceCategory.NONE  # Strongest turbulence category found (TURBULENCE mode)
    microburst: bool = False  # 1 = a wind shear event with microburst divergence was found (WINDSHEAR mode)
    elevations: int = 0  # Elevation angles in the scan's volume coverage pattern: 4 for SURVEILLANCE, 7 for MAPPING and PRECIPITATION, 1 for TURBULENCE and WINDSHEAR
    products_version: int = 0  # RDR_WX_PRODUCTS block version carrying this scan's products
    range_km: float = 0.0  # km, LSB 1, 10 .. 200, Instrumented range in effect; range bins beyond it are not scanned
    tilt: float = 0.0  # deg, LSB 180/32768, 0 .. 90, Antenna tilt in effect, reported as commanded; the sensor model has no antenna to tilt
    max_reflectivity: float = 0.0  # dBZ, LSB 1/128, -20 .. 65, Strongest return in the volume
    storm_cells: int = 0  # Storm cells the tracker holds (saturates at 255)
    precip_areas: int = 0  # Precipitation areas the analyzer found (saturates at 255)
    windshear_events: int = 0  # Wind shear events detected (saturates at 255)
    turbulence_cells: int = 0  # Turbulence cells detected (saturates at 255)
    vil_points: int = 0  # VIL points in the block
    precip_points: int = 0  # Precipitation points in the block
    vil_max: float = 0.0  # kg/m2, LSB 1/4, 0 .. 16383.75, Largest VIL in the field
