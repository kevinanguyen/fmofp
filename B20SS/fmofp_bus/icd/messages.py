        if not is_valid(Ssm, raw):
            return Status.INVALID_ENUM, None
        m.vertical_speed_ssm = Ssm(raw)
        raw = _w.get_field(words[0], 7, 6)
        if not is_valid(Ssm, raw):
            return Status.INVALID_ENUM, None
        m.altitude_ssm = Ssm(raw)
        raw = _w.get_field(words[0], 5, 4)
        if not is_valid(Ssm, raw):
            return Status.INVALID_ENUM, None
        m.clearance_ssm = Ssm(raw)
        m.vertical_speed = _w.decode_scaled(_w.from_twos(_w.get_field(words[1], 15, 0), 16), 1, 1)
        m.altitude = _w.decode_scaled(_w.get_field(words[2], 15, 0), 1, 1)
