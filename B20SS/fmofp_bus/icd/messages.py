@dataclass
class FcsGcasAlerts:
    """FCS_GCAS_ALERTS - Ground collision avoidance alerts. RT 5 · SA 14 · transmit (terminal to bus) · 4 words · 5 Hz.

    groundCollisionAvoidanceSys.py, evaluated every frame: PULLUP when vertical speed is at or below -4000 ft/min and altitude is below 2000 ft; otherwise SINK_RATE when vertical speed is at or below -2000 ft/min; TERRAIN when the terrain clearance is below 500 ft; ALT_LOW when altitude is below 200 ft and TERRAIN is not set. PULLUP, SINK_RATE and TERRAIN are severity 1 (WARNING); ALT_LOW is severity 2 (CAUTION). The terrain clearance is the terrain-following radar's minimum clearance over the profile ahead (FCS_TERRAIN, from v1.4); while the radar provides none (not operating, no profile, or the message stale) there is no TERRAIN alert and the clearance SSM is NO_COMPUTED_DATA, as the Python's GCAS treated a missing TFR value. The values that drove the decision ride along so a display can show them without another message.
    """
    RT: ClassVar[int] = 5
    SUBADDRESS: ClassVar[int] = 14
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 5
    WORDS: ClassVar[int] = 4

    status: GcasStatus = GcasStatus.OFF
    pullup: bool = False
    sink_rate: bool = False
    terrain: bool = False
    alt_low: bool = False
    vertical_speed_ssm: Ssm = Ssm.FAILURE_WARNING  # validity of vertical_speed
    altitude_ssm: Ssm = Ssm.FAILURE_WARNING  # validity of altitude
    clearance_ssm: Ssm = Ssm.FAILURE_WARNING  # validity of terrain_clearance
    vertical_speed: float = 0.0  # ft/min, LSB 1, -30000 .. 30000
    altitude: float = 0.0  # ft, LSB 1, 0 .. 65535
    terrain_clearance: float = 0.0  # ft, LSB 1, -32768 .. 32767, The radar's minimum clearance ahead; negative when terrain ahead is above the aircraft

    def encode(self) -> Tuple[Status, List[int]]:
        w = [0] * 4
        result = Status.OK
        if not is_valid(GcasStatus, self.status):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 15, 14, int(self.status))
        w[0] = _w.set_bit(w[0], 13, bool(self.pullup))
        w[0] = _w.set_bit(w[0], 12, bool(self.sink_rate))
        w[0] = _w.set_bit(w[0], 11, bool(self.terrain))
        w[0] = _w.set_bit(w[0], 10, bool(self.alt_low))
        if not is_valid(Ssm, self.vertical_speed_ssm):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 9, 8, int(self.vertical_speed_ssm))
        if not is_valid(Ssm, self.altitude_ssm):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 7, 6, int(self.altitude_ssm))
        if not is_valid(Ssm, self.clearance_ssm):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 5, 4, int(self.clearance_ssm))
        s, raw = _w.encode_scaled(self.vertical_speed, 1, 1, -30000, 30000)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 15, 0, _w.to_twos(raw, 16))
        s, raw = _w.encode_scaled(self.altitude, 1, 1, 0, 65535)
        result = worst(result, s)
        w[2] = _w.set_field(w[2], 15, 0, raw)
        s, raw = _w.encode_scaled(self.terrain_clearance, 1, 1, -32768, 32767)
        result = worst(result, s)
        w[3] = _w.set_field(w[3], 15, 0, _w.to_twos(raw, 16))
        return result, w

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["FcsGcasAlerts"]]:
        if len(words) != cls.WORDS:
            return Status.BAD_LENGTH, None
        m = cls()
        raw = _w.get_field(words[0], 15, 14)
        if not is_valid(GcasStatus, raw):
            return Status.INVALID_ENUM, None
        m.status = GcasStatus(raw)
        m.pullup = _w.get_bit(words[0], 13)
        m.sink_rate = _w.get_bit(words[0], 12)
        m.terrain = _w.get_bit(words[0], 11)
        m.alt_low = _w.get_bit(words[0], 10)
