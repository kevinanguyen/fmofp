        if not is_valid(TerminalState, raw):
            return Status.INVALID_ENUM, None
        m.state = TerminalState(raw)
        m.last_cmd_seq = _w.get_field(words[0], 7, 0)
        m.cmd_rejected = _w.get_bit(words[1], 15)
        m.healthy = _w.get_bit(words[1], 0)
