    state: TerminalState = TerminalState.STANDBY
    last_cmd_seq: int = 0  # cmd_seq of the last command processed (see Command sequence rule)
    cmd_rejected: bool = False  # 1 = the last TERM_CMD was rejected
    healthy: bool = False  # 1 = healthy (legacy health_status, bit 0)
    bit_in_progress: bool = False  # Same layout as the BIT word (mode code 19)
    bit_failed: bool = False  # Latched until RESET_REMOTE_TERMINAL
    fault_count: int = 0  # Faults since reset, saturates at 255
    icd_major: int = 0  # ICD version this terminal was built against
    icd_minor: int = 0
    last_sync: int = 0  # Data word of the last SYNCHRONIZE_WITH_DATA received

    def encode(self) -> Tuple[Status, List[int]]:
        w = [0] * 5
        result = Status.OK
        if not is_valid(TerminalState, self.state):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 15, 12, int(self.state))
        s, v = _w.check_uint(self.last_cmd_seq, 8)
