        result = worst(result, s)
        w[0] = _w.set_field(w[0], 15, 12, v)
        s, v = _w.check_uint(self.visible_mask, 12)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 11, 0, v)
        s, raw = _w.encode_scaled(self.pseudorange_1, 1, 16, 0, 1600000000)
        result = worst(result, s)
        w[1], w[2] = divmod(_w.to_twos32(raw), 0x10000)
        s, raw = _w.encode_scaled(self.pseudorange_2, 1, 16, 0, 1600000000)
        result = worst(result, s)
        w[3], w[4] = divmod(_w.to_twos32(raw), 0x10000)
