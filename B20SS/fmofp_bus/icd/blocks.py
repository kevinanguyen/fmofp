        result = worst(result, s)
        w[8] = _w.set_field(w[8], 15, 0, _w.to_twos(raw, 16))
        s, raw = _w.encode_scaled(self.centre_cross, 1, 1, -32768, 32767)
        result = worst(result, s)
        w[9] = _w.set_field(w[9], 15, 0, _w.to_twos(raw, 16))
        out = w + [len(self.pixel), len(self.change)]
        for record in self.pixel:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.change:
            s, words = record.encode()
            result = worst(result, s)
            out += words
