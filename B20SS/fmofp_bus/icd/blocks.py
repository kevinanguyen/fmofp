    track_quality: float = 0.0  # LSB 1/1000, 0 .. 1, Target.track_quality: 0 when designated, 0.5 when acquired, the radar's when updated, decaying while stale
    latitude: float = 0.0  # deg, LSB 180/2147483648, -90 .. 90
    longitude: float = 0.0  # deg, LSB 180/2147483648, -180 .. 179.9999999
    altitude: float = 0.0  # ft, LSB 1, 0 .. 65535
    speed: float = 0.0  # kt, LSB 1/10, 0 .. 6553.5
    heading: float = 0.0  # deg, LSB 360/65536, 0 .. 359.9945

    def encode(self) -> Tuple[Status, List[int]]:
        w = [0] * 9
        result = Status.OK
        s, v = _w.check_uint(self.id, 8)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 15, 8, v)
        if not is_valid(TargetKind, self.kind):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 7, 4, int(self.kind))
        if not is_valid(TargetStatus, self.status):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 3, 1, int(self.status))
        s, v = _w.check_uint(self.priority, 3)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 15, 13, v)
        if not is_valid(Weapon, self.weapon):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[1] = _w.set_field(w[1], 12, 10, int(self.weapon))
        s, raw = _w.encode_scaled(self.track_quality, 1, 1000, 0, 1000)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 9, 0, raw)
        s, raw = _w.encode_scaled(self.latitude, 45, 536870912, -1073741824, 1073741824)
        result = worst(result, s)
        w[2], w[3] = divmod(_w.to_twos32(raw), 0x10000)
        s, raw = _w.encode_scaled(self.longitude, 45, 536870912, -2147483648, 2147483647)
        result = worst(result, s)
        w[4], w[5] = divmod(_w.to_twos32(raw), 0x10000)
        s, raw = _w.encode_scaled(self.altitude, 1, 1, 0, 65535)
        result = worst(result, s)
        w[6] = _w.set_field(w[6], 15, 0, raw)
        s, raw = _w.encode_scaled(self.speed, 1, 10, 0, 65535)
        result = worst(result, s)
        w[7] = _w.set_field(w[7], 15, 0, raw)
        s, raw = _w.encode_scaled(self.heading, 45, 8192, 0, 65535)
        result = worst(result, s)
        w[8] = _w.set_field(w[8], 15, 0, raw)
        return result, w

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["MsnPlanTarget"]]:
        if len(words) != cls.WORDS:
            return Status.BAD_LENGTH, None
        m = cls()
        m.id = _w.get_field(words[0], 15, 8)
        raw = _w.get_field(words[0], 7, 4)
        if not is_valid(TargetKind, raw):
            return Status.INVALID_ENUM, None
        m.kind = TargetKind(raw)
        raw = _w.get_field(words[0], 3, 1)
        if not is_valid(TargetStatus, raw):
            return Status.INVALID_ENUM, None
        m.status = TargetStatus(raw)
        m.priority = _w.get_field(words[1], 15, 13)
        raw = _w.get_field(words[1], 12, 10)
        if not is_valid(Weapon, raw):
            return Status.INVALID_ENUM, None
        m.weapon = Weapon(raw)
        m.track_quality = _w.decode_scaled(_w.get_field(words[1], 9, 0), 1, 1000)
        m.latitude = _w.decode_scaled(_w.from_twos32((words[2] << 16) | words[3]), 45, 536870912)
        m.longitude = _w.decode_scaled(_w.from_twos32((words[4] << 16) | words[5]), 45, 536870912)
        m.altitude = _w.decode_scaled(_w.get_field(words[6], 15, 0), 1, 1)
        m.speed = _w.decode_scaled(_w.get_field(words[7], 15, 0), 1, 10)
        m.heading = _w.decode_scaled(_w.get_field(words[8], 15, 0), 45, 8192)
        return Status.OK, m


