@dataclass
class RdrWxProducts:
    """RDR_WX_PRODUCTS - Weather radar products. RT 9 · descriptor SA 6 · segment SA 7 · 50 Hz.

    Everything one scan produced, published as one block when the scan completes so a consumer always draws a consistent picture (README section 8). Which sections are filled depends on the mode: SURVEILLANCE fills vil, precip and cells; MAPPING and PRECIPITATION fill precip and areas; WINDSHEAR fills windshear; TURBULENCE fills turbulence. Positions are polar from the aircraft: true azimuth and range. The record limits apply after the selection described in the README (the Python's own limits for the VIL and precipitation points; new for the rest); the counts before the limits are in RDR_WX_SCAN. The segment subaddress is polled every frame, so an 18-segment block arrives in 0.36 s, well inside the 1.2 s scan.
    """
    RT: ClassVar[int] = 9
    DESCRIPTOR_SUBADDRESS: ClassVar[int] = 6
    SEGMENT_SUBADDRESS: ClassVar[int] = 7
    RATE_HZ: ClassVar[int] = 50
    HEADER_WORDS: ClassVar[int] = 2
    SECTIONS: ClassVar[Tuple[str, ...]] = ('vil', 'precip', 'cells', 'areas', 'windshear', 'turbulence', )
    MAX_PAYLOAD_WORDS: ClassVar[int] = 548
    MAX_VIL: ClassVar[int] = 20
    MAX_PRECIP: ClassVar[int] = 15
    MAX_CELLS: ClassVar[int] = 12
    MAX_AREAS: ClassVar[int] = 12
    MAX_WINDSHEAR: ClassVar[int] = 20
    MAX_TURBULENCE: ClassVar[int] = 20

    scan_id: int = 0  # Scan these products come from (RDR_WX_SCAN.scan_id)
    mode: WeatherMode = WeatherMode.NONE  # Mode of that scan; NONE with every section empty when the radar is not scanning
    microburst: bool = False  # 1 = a microburst was detected (WINDSHEAR mode)
    max_turbulence: TurbulenceCategory = TurbulenceCategory.NONE  # Strongest turbulence category (TURBULENCE mode)
    max_reflectivity: float = 0.0  # dBZ, LSB 1/128, -20 .. 65, Strongest return in the volume
    vil: List[RdrWxProductsVil] = field(default_factory=list)
    precip: List[RdrWxProductsPrecip] = field(default_factory=list)
    cells: List[RdrWxProductsCells] = field(default_factory=list)
    areas: List[RdrWxProductsAreas] = field(default_factory=list)
    windshear: List[RdrWxProductsWindshear] = field(default_factory=list)
    turbulence: List[RdrWxProductsTurbulence] = field(default_factory=list)

    def encode(self) -> Tuple[Status, List[int]]:
        if len(self.vil) > self.MAX_VIL or len(self.precip) > self.MAX_PRECIP or len(self.cells) > self.MAX_CELLS or len(self.areas) > self.MAX_AREAS or len(self.windshear) > self.MAX_WINDSHEAR or len(self.turbulence) > self.MAX_TURBULENCE:
            return Status.INVALID_ARGUMENT, []
        w = [0] * 2
        result = Status.OK
        s, v = _w.check_uint(self.scan_id, 8)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 15, 8, v)
        if not is_valid(WeatherMode, self.mode):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 7, 4, int(self.mode))
        w[0] = _w.set_bit(w[0], 3, bool(self.microburst))
        if not is_valid(TurbulenceCategory, self.max_turbulence):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 2, 0, int(self.max_turbulence))
        s, raw = _w.encode_scaled(self.max_reflectivity, 1, 128, -2560, 8320)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 15, 0, _w.to_twos(raw, 16))
        out = w + [len(self.vil), len(self.precip), len(self.cells), len(self.areas), len(self.windshear), len(self.turbulence)]
        for record in self.vil:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.precip:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.cells:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.areas:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.windshear:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.turbulence:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        return result, out

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["RdrWxProducts"]]:
        if len(words) < cls.HEADER_WORDS + len(cls.SECTIONS):
            return Status.BAD_LENGTH, None
        m = cls()
        m.scan_id = _w.get_field(words[0], 15, 8)
        raw = _w.get_field(words[0], 7, 4)
        if not is_valid(WeatherMode, raw):
            return Status.INVALID_ENUM, None
        m.mode = WeatherMode(raw)
        m.microburst = _w.get_bit(words[0], 3)
        raw = _w.get_field(words[0], 2, 0)
        if not is_valid(TurbulenceCategory, raw):
            return Status.INVALID_ENUM, None
        m.max_turbulence = TurbulenceCategory(raw)
        m.max_reflectivity = _w.decode_scaled(_w.from_twos(_w.get_field(words[1], 15, 0), 16), 1, 128)
        pos = cls.HEADER_WORDS
        counts = words[pos:pos + len(cls.SECTIONS)]
        pos += len(cls.SECTIONS)
        if counts[0] > cls.MAX_VIL or counts[1] > cls.MAX_PRECIP or counts[2] > cls.MAX_CELLS or counts[3] > cls.MAX_AREAS or counts[4] > cls.MAX_WINDSHEAR or counts[5] > cls.MAX_TURBULENCE:
            return Status.BAD_LENGTH, None
        if len(words) != pos + counts[0] * RdrWxProductsVil.WORDS + counts[1] * RdrWxProductsPrecip.WORDS + counts[2] * RdrWxProductsCells.WORDS + counts[3] * RdrWxProductsAreas.WORDS + counts[4] * RdrWxProductsWindshear.WORDS + counts[5] * RdrWxProductsTurbulence.WORDS:
            return Status.BAD_LENGTH, None
        for _ in range(counts[0]):
            s, record = RdrWxProductsVil.decode(words[pos:pos + RdrWxProductsVil.WORDS])
            if s != Status.OK:
                return s, None
            m.vil.append(record)
            pos += RdrWxProductsVil.WORDS
        for _ in range(counts[1]):
            s, record = RdrWxProductsPrecip.decode(words[pos:pos + RdrWxProductsPrecip.WORDS])
            if s != Status.OK:
                return s, None
            m.precip.append(record)
            pos += RdrWxProductsPrecip.WORDS
        for _ in range(counts[2]):
            s, record = RdrWxProductsCells.decode(words[pos:pos + RdrWxProductsCells.WORDS])
            if s != Status.OK:
                return s, None
            m.cells.append(record)
            pos += RdrWxProductsCells.WORDS
        for _ in range(counts[3]):
            s, record = RdrWxProductsAreas.decode(words[pos:pos + RdrWxProductsAreas.WORDS])
            if s != Status.OK:
                return s, None
            m.areas.append(record)
            pos += RdrWxProductsAreas.WORDS
        for _ in range(counts[4]):
            s, record = RdrWxProductsWindshear.decode(words[pos:pos + RdrWxProductsWindshear.WORDS])
            if s != Status.OK:
                return s, None
            m.windshear.append(record)
            pos += RdrWxProductsWindshear.WORDS
        for _ in range(counts[5]):
            s, record = RdrWxProductsTurbulence.decode(words[pos:pos + RdrWxProductsTurbulence.WORDS])
            if s != Status.OK:
                return s, None
            m.turbulence.append(record)
            pos += RdrWxProductsTurbulence.WORDS
        return Status.OK, m


