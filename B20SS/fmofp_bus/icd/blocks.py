    change: List[RdrSarImageChange] = field(default_factory=list)

    def encode(self) -> Tuple[Status, List[int]]:
        if len(self.pixel) > self.MAX_PIXEL or len(self.change) > self.MAX_CHANGE:
            return Status.INVALID_ARGUMENT, []
        w = [0] * 10
        result = Status.OK
        s, v = _w.check_uint(self.image_seq, 8)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 15, 8, v)
        if not is_valid(SarMode, self.mode):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 7, 4, int(self.mode))
        s, v = _w.check_uint(self.changes, 4)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 3, 0, v)
        s, raw = _w.encode_scaled(self.resolution, 1, 100, 0, 65535)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 15, 0, raw)
        s, raw = _w.encode_scaled(self.pixel_size, 1, 100, 0, 65535)
        result = worst(result, s)
        w[2] = _w.set_field(w[2], 15, 0, raw)
        s, raw = _w.encode_scaled(self.centre_latitude, 45, 536870912, -1073741824, 1073741824)
        result = worst(result, s)
        w[3], w[4] = divmod(_w.to_twos32(raw), 0x10000)
