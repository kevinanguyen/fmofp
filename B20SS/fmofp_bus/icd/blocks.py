@dataclass
class RdrWxProducts:
    """RDR_WX_PRODUCTS - Weather radar products. RT 9 · descriptor SA 6 · segment SA 7 · 25 Hz.

    Everything one scan produced, published as one block when the scan completes so a consumer always draws a consistent picture (README section 8). Which sections are filled depends on the mode: SURVEILLANCE fills vil, precip and cells; MAPPING and PRECIPITATION fill precip and areas; WINDSHEAR fills windshear; TURBULENCE fills turbulence. Positions are polar from the aircraft: true azimuth and range. The record limits apply after the selection described in the README (the Python's own limits for the VIL and precipitation points; new for the rest); the counts before the limits are in RDR_WX_SCAN. The segment subaddress is polled every frame, so an 18-segment block arrives in 0.36 s, well inside the 1.2 s scan.
    """
    RT: ClassVar[int] = 9
    DESCRIPTOR_SUBADDRESS: ClassVar[int] = 6
    SEGMENT_SUBADDRESS: ClassVar[int] = 7
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 25
    HEADER_WORDS: ClassVar[int] = 2
    SECTIONS: ClassVar[Tuple[str, ...]] = ('vil', 'precip', 'cells', 'areas', 'windshear', 'turbulence', )
    MAX_PAYLOAD_WORDS: ClassVar[int] = 548
    MAX_VIL: ClassVar[int] = 20
    MAX_PRECIP: ClassVar[int] = 15
    MAX_CELLS: ClassVar[int] = 12
    MAX_AREAS: ClassVar[int] = 12
    MAX_WINDSHEAR: ClassVar[int] = 20
    MAX_TURBULENCE: ClassVar[int] = 20

    scan_id: int = 0  # Scan these products come from (RDR_WX_SCAN.scan_id)
    mode: WeatherMode = WeatherMode.NONE  # Mode of that scan; NONE with every section empty when the radar is not scanning
    microburst: bool = False  # 1 = a microburst was detected (WINDSHEAR mode)
    max_turbulence: TurbulenceCategory = TurbulenceCategory.NONE  # Strongest turbulence category (TURBULENCE mode)
    max_reflectivity: float = 0.0  # dBZ, LSB 1/128, -20 .. 65, Strongest return in the volume
    vil: List[RdrWxProductsVil] = field(default_factory=list)
    precip: List[RdrWxProductsPrecip] = field(default_factory=list)
    cells: List[RdrWxProductsCells] = field(default_factory=list)
    areas: List[RdrWxProductsAreas] = field(default_factory=list)
    windshear: List[RdrWxProductsWindshear] = field(default_factory=list)
    turbulence: List[RdrWxProductsTurbulence] = field(default_factory=list)

    def encode(self) -> Tuple[Status, List[int]]:
        if len(self.vil) > self.MAX_VIL or len(self.precip) > self.MAX_PRECIP or len(self.cells) > self.MAX_CELLS or len(self.areas) > self.MAX_AREAS or len(self.windshear) > self.MAX_WINDSHEAR or len(self.turbulence) > self.MAX_TURBULENCE:
            return Status.INVALID_ARGUMENT, []
        w = [0] * 2
        result = Status.OK
