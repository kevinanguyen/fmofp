@dataclass
class RdrAewcTracks:
    """RDR_AEWC_TRACKS - AEWC tracks and sector scan. RT 9 · descriptor SA 12 · segment SA 13 · 10 Hz.

    aewc_radar._handle_track_request's track data and _handle_sector_scan_request's sector data in one block (v1.12): every track the radar holds, classified by its own rule (a cross-section under 0.1 m2 STEALTH, else a speed over 400 m/s FIGHTER, else more than 30 km above or below the aircraft HIGH_ALT, else UNKNOWN), with the signal-to-noise ratio of its radar equation and the confidence snr / 30; and the six 60-degree sectors (azimuth counter-clockwise from east, as the Python measured it) with their scan progress, the tracks detected in each, the priority manager's score and dwell share and the electronic protection's assessment. Positions are Cartesian metres east, north and up of the aircraft. Republished no more often than every 35 frames: its six segments take 30 frames at 10 Hz.
    """
    RT: ClassVar[int] = 9
    DESCRIPTOR_SUBADDRESS: ClassVar[int] = 12
    SEGMENT_SUBADDRESS: ClassVar[int] = 13
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 10
    HEADER_WORDS: ClassVar[int] = 3
    SECTIONS: ClassVar[Tuple[str, ...]] = ('track', 'sector', )
    MAX_PAYLOAD_WORDS: ClassVar[int] = 173
    MAX_TRACK: ClassVar[int] = 12
    MAX_SECTOR: ClassVar[int] = 6

    update_seq: int = 0  # Increments (mod 256) with every track update the block reflects
    mode: AewcMode = AewcMode.NONE  # Mode the tracks were made in; NONE with no tracks when the radar is not operating
    scan_azimuth_start: float = 0.0  # deg, LSB 180/32768, -180 .. 179.9945, The commanded sector's start (RDR_AEWC_MODE_CMD), relative to the nose
    scan_azimuth_end: float = 0.0  # deg, LSB 180/32768, -180 .. 179.9945, The commanded sector's end
    track: List[RdrAewcTracksTrack] = field(default_factory=list)
    sector: List[RdrAewcTracksSector] = field(default_factory=list)

    def encode(self) -> Tuple[Status, List[int]]:
        if len(self.track) > self.MAX_TRACK or len(self.sector) > self.MAX_SECTOR:
            return Status.INVALID_ARGUMENT, []
        w = [0] * 3
        result = Status.OK
        s, v = _w.check_uint(self.update_seq, 8)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 15, 8, v)
        if not is_valid(AewcMode, self.mode):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 7, 4, int(self.mode))
        s, raw = _w.encode_scaled(self.scan_azimuth_start, 45, 8192, -32768, 32767)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 15, 0, _w.to_twos(raw, 16))
        s, raw = _w.encode_scaled(self.scan_azimuth_end, 45, 8192, -32768, 32767)
        result = worst(result, s)
        w[2] = _w.set_field(w[2], 15, 0, _w.to_twos(raw, 16))
        out = w + [len(self.track), len(self.sector)]
        for record in self.track:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.sector:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        return result, out

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["RdrAewcTracks"]]:
        if len(words) < cls.HEADER_WORDS + len(cls.SECTIONS):
            return Status.BAD_LENGTH, None
        m = cls()
        m.update_seq = _w.get_field(words[0], 15, 8)
        raw = _w.get_field(words[0], 7, 4)
        if not is_valid(AewcMode, raw):
            return Status.INVALID_ENUM, None
        m.mode = AewcMode(raw)
        m.scan_azimuth_start = _w.decode_scaled(_w.from_twos(_w.get_field(words[1], 15, 0), 16), 45, 8192)
        m.scan_azimuth_end = _w.decode_scaled(_w.from_twos(_w.get_field(words[2], 15, 0), 16), 45, 8192)
        pos = cls.HEADER_WORDS
        counts = words[pos:pos + len(cls.SECTIONS)]
        pos += len(cls.SECTIONS)
        if counts[0] > cls.MAX_TRACK or counts[1] > cls.MAX_SECTOR:
            return Status.BAD_LENGTH, None
        if len(words) != pos + counts[0] * RdrAewcTracksTrack.WORDS + counts[1] * RdrAewcTracksSector.WORDS:
            return Status.BAD_LENGTH, None
        for _ in range(counts[0]):
            s, record = RdrAewcTracksTrack.decode(words[pos:pos + RdrAewcTracksTrack.WORDS])
            if s != Status.OK:
                return s, None
            m.track.append(record)
            pos += RdrAewcTracksTrack.WORDS
        for _ in range(counts[1]):
            s, record = RdrAewcTracksSector.decode(words[pos:pos + RdrAewcTracksSector.WORDS])
            if s != Status.OK:
                return s, None
            m.sector.append(record)
            pos += RdrAewcTracksSector.WORDS
        return Status.OK, m


