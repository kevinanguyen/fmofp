@dataclass
class MsnPlan:
    """MSN_PLAN - Mission plan: the route, the targets, the order of battle. RT 6 · descriptor SA 12 · segment SA 13 · 10 Hz.

    What missionService.get_data(), get_nav_data() and get_oob() handed the MFD's mission page and the TSD (v1.16): RouteManager.get_full_route() (every waypoint with its name, type, position, altitude and ETE, in route order, those already passed flagged), Targeting.get_prioritised() (the targets neither destroyed nor lost, by priority then track quality), and every unit of the order of battle with its affiliation, kind, status and threat level. Published when a command or the route's progress changes it, no sooner than 75 frames after the last publication (its thirteen segments take 65 frames at 10 Hz), and every 150 frames while a route is being flown, as the ETEs move.
    """
    RT: ClassVar[int] = 6
    DESCRIPTOR_SUBADDRESS: ClassVar[int] = 12
    SEGMENT_SUBADDRESS: ClassVar[int] = 13
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 10
    HEADER_WORDS: ClassVar[int] = 3
    SECTIONS: ClassVar[Tuple[str, ...]] = ('waypoint', 'target', 'unit', )
    MAX_PAYLOAD_WORDS: ClassVar[int] = 382
    MAX_WAYPOINT: ClassVar[int] = 16
    MAX_TARGET: ClassVar[int] = 8
    MAX_UNIT: ClassVar[int] = 16

    plan_seq: int = 0  # The publication's number, 1-255 round and round
    phase: MissionPhase = MissionPhase.PLANNING
    active_index: int = 0  # RouteManager._active_idx, as MSN_STATUS
    distance_to_next: float = 0.0  # nm, LSB 1/10, 0 .. 6553.5, To the active waypoint; 0 without one
    bearing_to_next: float = 0.0  # deg, LSB 360/65536, 0 .. 359.9945, True; 0 without an active waypoint
    waypoint: List[MsnPlanWaypoint] = field(default_factory=list)
    target: List[MsnPlanTarget] = field(default_factory=list)
    unit: List[MsnPlanUnit] = field(default_factory=list)

    def encode(self) -> Tuple[Status, List[int]]:
        if len(self.waypoint) > self.MAX_WAYPOINT or len(self.target) > self.MAX_TARGET or len(self.unit) > self.MAX_UNIT:
            return Status.INVALID_ARGUMENT, []
        w = [0] * 3
        result = Status.OK
        s, v = _w.check_uint(self.plan_seq, 8)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 15, 8, v)
        if not is_valid(MissionPhase, self.phase):
            result = worst(result, Status.INVALID_ARGUMENT)
        w[0] = _w.set_field(w[0], 7, 5, int(self.phase))
        s, v = _w.check_uint(self.active_index, 5)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 4, 0, v)
        s, raw = _w.encode_scaled(self.distance_to_next, 1, 10, 0, 65535)
        result = worst(result, s)
        w[1] = _w.set_field(w[1], 15, 0, raw)
        s, raw = _w.encode_scaled(self.bearing_to_next, 45, 8192, 0, 65535)
        result = worst(result, s)
        w[2] = _w.set_field(w[2], 15, 0, raw)
        out = w + [len(self.waypoint), len(self.target), len(self.unit)]
        for record in self.waypoint:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.target:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.unit:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        return result, out

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["MsnPlan"]]:
        if len(words) < cls.HEADER_WORDS + len(cls.SECTIONS):
            return Status.BAD_LENGTH, None
        m = cls()
        m.plan_seq = _w.get_field(words[0], 15, 8)
        raw = _w.get_field(words[0], 7, 5)
        if not is_valid(MissionPhase, raw):
            return Status.INVALID_ENUM, None
        m.phase = MissionPhase(raw)
        m.active_index = _w.get_field(words[0], 4, 0)
        m.distance_to_next = _w.decode_scaled(_w.get_field(words[1], 15, 0), 1, 10)
        m.bearing_to_next = _w.decode_scaled(_w.get_field(words[2], 15, 0), 45, 8192)
        pos = cls.HEADER_WORDS
        counts = words[pos:pos + len(cls.SECTIONS)]
        pos += len(cls.SECTIONS)
        if counts[0] > cls.MAX_WAYPOINT or counts[1] > cls.MAX_TARGET or counts[2] > cls.MAX_UNIT:
            return Status.BAD_LENGTH, None
        if len(words) != pos + counts[0] * MsnPlanWaypoint.WORDS + counts[1] * MsnPlanTarget.WORDS + counts[2] * MsnPlanUnit.WORDS:
            return Status.BAD_LENGTH, None
        for _ in range(counts[0]):
            s, record = MsnPlanWaypoint.decode(words[pos:pos + MsnPlanWaypoint.WORDS])
            if s != Status.OK:
                return s, None
            m.waypoint.append(record)
            pos += MsnPlanWaypoint.WORDS
        for _ in range(counts[1]):
            s, record = MsnPlanTarget.decode(words[pos:pos + MsnPlanTarget.WORDS])
            if s != Status.OK:
                return s, None
            m.target.append(record)
            pos += MsnPlanTarget.WORDS
        for _ in range(counts[2]):
            s, record = MsnPlanUnit.decode(words[pos:pos + MsnPlanUnit.WORDS])
            if s != Status.OK:
                return s, None
            m.unit.append(record)
            pos += MsnPlanUnit.WORDS
        return Status.OK, m


