class PlantGround:
    """PLANT_GROUND - Ground scene for the synthetic aperture radar, from the plant. RT 27 · descriptor SA 10 · segment SA 11 · 10 Hz.

    The ground the synthetic aperture radar images (v1.13): the plant's training range (fmofp_plant.ground), laid out along the northbound track from home, as point scatterers (buildings, the vehicles on the roads and the ship on the lake: a square of `size` on a side at a `brightness`), linear features (roads and a river: lines of a `width`) and areas (a lake, forests, a town: discs). Positions are WGS-84, so the radar places them against the navigation it is given; what a feature is does not reach the picture, only its backscatter. The vehicles and the ship move at the plant's walk rate; published once a second (its four segments take 20 frames at 10 Hz).
    """
    RT: ClassVar[int] = 27
    DESCRIPTOR_SUBADDRESS: ClassVar[int] = 10
    SEGMENT_SUBADDRESS: ClassVar[int] = 11
    DIRECTION: ClassVar[str] = "T"
    RATE_HZ: ClassVar[int] = 10
    HEADER_WORDS: ClassVar[int] = 2
    SECTIONS: ClassVar[Tuple[str, ...]] = ('point', 'line', 'area', )
    MAX_PAYLOAD_WORDS: ClassVar[int] = 119
    MAX_POINT: ClassVar[int] = 10
    MAX_LINE: ClassVar[int] = 3
    MAX_AREA: ClassVar[int] = 4

    scene_seq: int = 0  # Increments (mod 256) with every publication
    point: List[PlantGroundPoint] = field(default_factory=list)
    line: List[PlantGroundLine] = field(default_factory=list)
    area: List[PlantGroundArea] = field(default_factory=list)

    def encode(self) -> Tuple[Status, List[int]]:
        if len(self.point) > self.MAX_POINT or len(self.line) > self.MAX_LINE or len(self.area) > self.MAX_AREA:
            return Status.INVALID_ARGUMENT, []
        w = [0] * 2
        result = Status.OK
        s, v = _w.check_uint(self.scene_seq, 8)
        result = worst(result, s)
        w[0] = _w.set_field(w[0], 15, 8, v)
        out = w + [len(self.point), len(self.line), len(self.area)]
        for record in self.point:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.line:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        for record in self.area:
            s, words = record.encode()
            result = worst(result, s)
            out += words
        return result, out

    @classmethod
    def decode(cls, words) -> Tuple[Status, Optional["PlantGround"]]:
        if len(words) < cls.HEADER_WORDS + len(cls.SECTIONS):
            return Status.BAD_LENGTH, None
        m = cls()
        m.scene_seq = _w.get_field(words[0], 15, 8)
        pos = cls.HEADER_WORDS
        counts = words[pos:pos + len(cls.SECTIONS)]
        pos += len(cls.SECTIONS)
        if counts[0] > cls.MAX_POINT or counts[1] > cls.MAX_LINE or counts[2] > cls.MAX_AREA:
            return Status.BAD_LENGTH, None
        if len(words) != pos + counts[0] * PlantGroundPoint.WORDS + counts[1] * PlantGroundLine.WORDS + counts[2] * PlantGroundArea.WORDS:
            return Status.BAD_LENGTH, None
        for _ in range(counts[0]):
            s, record = PlantGroundPoint.decode(words[pos:pos + PlantGroundPoint.WORDS])
            if s != Status.OK:
                return s, None
            m.point.append(record)
            pos += PlantGroundPoint.WORDS
        for _ in range(counts[1]):
            s, record = PlantGroundLine.decode(words[pos:pos + PlantGroundLine.WORDS])
            if s != Status.OK:
                return s, None
            m.line.append(record)
            pos += PlantGroundLine.WORDS
        for _ in range(counts[2]):
            s, record = PlantGroundArea.decode(words[pos:pos + PlantGroundArea.WORDS])
            if s != Status.OK:
                return s, None
            m.area.append(record)
            pos += PlantGroundArea.WORDS
        return Status.OK, m


